// Icon registry - maps icon names from config to components
type IconComponent = ({ className }: IconProps) => JSX.Element;

export const iconRegistry: Record<IconName, IconComponent> = {
  'video-camera': VideoCameraIcon,
  'game-controller': GameControllerIcon,
  'film': FilmIcon,
  'music': MusicIcon,
  'book': BookIcon,
  'star': StarIcon,
  'heart': HeartIcon,
  'folder': FolderIcon,
  'smartphone': SmartphoneIcon,
  'zap': ZapIcon,
};

// Helper component to render icon by name
export function DynamicIcon({ name, className }: { name: IconName; className?: string }) {
  const IconComponent = iconRegistry[name] || FolderIcon;
  return <IconComponent className={className} />;
}
